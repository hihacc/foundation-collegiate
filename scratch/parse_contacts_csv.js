function parseContactsCsv(raw) {
  const lines = raw.split('\n');
  const contactsMap = new Map();

  for (let i = 1; i < lines.length; i++) {
    const line = lines[i].trim();
    if (!line) continue;

    const cols = line.split(',');
    const fn = (cols[0] || '').trim();
    const mn = (cols[1] || '').trim();
    const ln = (cols[2] || '').trim();
    const nickname = (cols[8] || '').trim();
    const orgTitle = (cols[11] || '').trim();
    const phoneVal = (cols[20] || cols[22] || cols[24] || '').trim();

    let name = [fn, mn, ln].filter(Boolean).join(' ').trim();
    if (!name && nickname) name = nickname;
    if (!name && orgTitle) name = orgTitle;
    
    // Extract phone
    let rawPhone = phoneVal.split(':::')[0].trim();
    let cleanPhone = rawPhone.replace(/[^0-9]/g, '');
    if (!cleanPhone) continue;

    // Normalize phone number to PK format 03XXXXXXXXX / 923XXXXXXXXX
    if (cleanPhone.startsWith('92')) {
      cleanPhone = '0' + cleanPhone.slice(2);
    } else if (cleanPhone.startsWith('0092')) {
      cleanPhone = '0' + cleanPhone.slice(4);
    } else if (!cleanPhone.startsWith('0') && cleanPhone.length === 10) {
      cleanPhone = '0' + cleanPhone;
    }

    if (cleanPhone.length < 10) continue;

    // Fallback name if still blank
    if (!name) {
      name = `Student (${cleanPhone})`;
    }

    // Determine category / role based on name content
    let role = 'Student / Contact';
    const lowerName = name.toLowerCase();
    if (lowerName.includes('father') || lowerName.includes('ftr')) role = 'Parent (Father)';
    else if (lowerName.includes('mother') || lowerName.includes('mot')) role = 'Parent (Mother)';
    else if (lowerName.includes('miss') || lowerName.includes('sir') || lowerName.includes('tutor') || lowerName.includes('teacher')) role = 'Faculty / Teacher';
    else if (lowerName.includes('xi') && lowerName.includes('com')) role = 'Student (XI-Commerce)';
    else if (lowerName.includes('xi') && (lowerName.includes('sci') || lowerName.includes('sc') || lowerName.includes('pe') || lowerName.includes('pm'))) role = 'Student (XI-Science)';
    else if (lowerName.includes('xi')) role = 'Student (XI)';
    else if (lowerName.includes('xii') && lowerName.includes('com')) role = 'Student (XII-Commerce)';
    else if (lowerName.includes('xii') && (lowerName.includes('sci') || lowerName.includes('sc') || lowerName.includes('pm'))) role = 'Student (XII-Science)';
    else if (lowerName.includes('xii')) role = 'Student (XII)';
    else if (lowerName.includes('ix') || lowerName.includes('class 9') || lowerName.includes('class ix')) role = 'Student (Class IX)';
    else if (lowerName.includes('x') || lowerName.includes('class 10') || lowerName.includes('class x')) role = 'Student (Class X)';
    else if (lowerName.includes('bcom') || lowerName.includes('adc') || lowerName.includes('b.com')) role = 'Student (ADC / B.Com)';
    else if (lowerName.includes('junior') || lowerName.includes('vii') || lowerName.includes('viii')) role = 'Student (Junior Section)';

    if (!contactsMap.has(cleanPhone)) {
      contactsMap.set(cleanPhone, {
        id: 'csv_' + cleanPhone,
        name: name,
        phone: cleanPhone,
        role: role
      });
    }
  }

  return Array.from(contactsMap.values());
}

